/**
 * Shared formatting helpers for the Forge report renderers.
 *
 * Pure + deterministic: same input always yields the same string. Locale-free
 * (no Intl), timezone-free: timestamps are printed exactly as recorded
 * (ISO-8601 strings compare correctly lexicographically when produced by the
 * same adapter). Missing values render as "-" — never fabricated.
 */
import type { AgentStats, Insight, RunReport, RunTotals } from '../core/model.js';

