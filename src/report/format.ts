const HTML_ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

/** Attribute-safe HTML escaping: & < > " ' — mandatory for ALL dynamic strings. */
export function escapeHtml(s: string): string {
  return String(s).replace(/[&<>"']/g, (ch) => HTML_ESCAPES[ch] ?? ch);
}

/** Append "..." when longer than `max` (truncate raw text BEFORE escaping). */
export function truncate(s: string, max: number): string {
  const str = String(s);
  if (max <= 0) return '';
  if (str.length <= max) return str;
  const ell = '...';
  if (max <= ell.length) return str.slice(0, max);
  return str.slice(0, max - ell.length).trimEnd() + ell;
}

/** Collapse all whitespace runs to single spaces. */
export function oneLine(s: string): string {
  return String(s).replace(/\s+/g, ' ').trim();
}

/** Map every character outside printable ASCII (32-126) to '?'. */
export function ascii(s: string): string {
  return String(s).replace(/[^\x20-\x7E]/g, '?');
}

/** Sanitize arbitrary external text for a single-line ASCII terminal cell. */
export function cell(s: unknown): string {
  return ascii(oneLine(s === undefined || s === null ? '' : String(s)));
}

/** Word-wrap to at most `width` columns (words longer than the line are cut). */
export function wrapWords(text: string, width: number): string[] {
  if (width < 1) width = 1;
  const words = oneLine(text).split(' ').filter(Boolean);
  const lines: string[] = [];
  let cur = '';
  for (const rawWord of words) {
    const word = rawWord.length > width ? truncate(rawWord, width) : rawWord;
    if (!cur) cur = word;
    else if (cur.length + 1 + word.length <= width) cur += ` ${word}`;
    else {
      lines.push(cur);
      cur = word;
    }
  }
  lines.push(cur);
  return lines;
}

