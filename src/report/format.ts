export interface OrderedAgent {
  agent: AgentStats;
  depth: number;
}

/**
 * Depth-first swarm-tree order: parents immediately followed by their
 * children. Roots and sibling groups sort by display name then id, so the
 * order is deterministic for any input array order. Cycle-safe.
 */
export function orderAgents(agents: AgentStats[]): OrderedAgent[] {
  const byId = new Set(agents.map((a) => a.agentId));
  const childrenOf = new Map<string, AgentStats[]>();
  const roots: AgentStats[] = [];
  for (const a of agents) {
    if (a.parentAgentId && byId.has(a.parentAgentId)) {
      const list = childrenOf.get(a.parentAgentId) ?? [];
      list.push(a);
      childrenOf.set(a.parentAgentId, list);
    } else {
      roots.push(a);
    }
  }
  const byName = (x: AgentStats, y: AgentStats): number =>
    displayName(x).localeCompare(displayName(y)) || x.agentId.localeCompare(y.agentId);
  const seen = new Set<string>();
  const out: OrderedAgent[] = [];
  const visit = (a: AgentStats, depth: number): void => {
    if (seen.has(a.agentId)) return;
    seen.add(a.agentId);
    out.push({ agent: a, depth });
    for (const child of (childrenOf.get(a.agentId) ?? []).slice().sort(byName)) {
      visit(child, depth + 1);
    }
  };
  for (const root of roots.slice().sort(byName)) visit(root, 0);
  return out;
}

export function displayName(a: AgentStats): string {
  return a.name && a.name.trim() !== '' ? a.name.trim() : a.agentId;
}

/** Model ids attributed to an agent, most-used first. */
export function modelsUsed(models: Record<string, number>): string {
  return Object.entries(models)
    .filter(([, tokens]) => Number.isFinite(tokens))
    .sort((x, y) => y[1] - x[1] || x[0].localeCompare(y[0]))
    .map(([id]) => id)
    .join(', ');
}

/**
 * Visible caveat for the estimated-cost figure, or null when the estimate
 * covers everything. RunTotals carries no per-record counter, so the notice
 * speaks of "some records" instead of a fabricated N.
 */
export function costNotice(totals: RunTotals): string | null {
  if (totals.costUsd !== undefined) {
    return totals.costKnown
      ? null
      : 'Pricing was unknown for some usage records; the estimate covers known-priced models only.';
  }
  return totals.costKnown
    ? 'No token usage in this run matched the pricing table.'
    : 'Pricing was unknown for some usage records; no total cost estimate is possible.';
}

/**
 * Activity window (earliest task start -> latest task end, falling back to
 * meta.createdAt). Purely string-based: no clock reads, no timezone math.
 */
export function runWindow(r: RunReport): { start: string; end: string } {
  let start: string | undefined;
  let end: string | undefined;
  for (const t of r.tasks) {
    if (t.startedAt && (start === undefined || t.startedAt < start)) start = t.startedAt;
    const stop = t.endedAt ?? t.startedAt;
    if (stop && (end === undefined || stop > end)) end = stop;
  }
  return { start: start ?? r.meta.createdAt, end: end ?? r.meta.createdAt };
}

/** Insights sorted warn-first, original order preserved within a severity. */
export function sortedInsights(r: RunReport): Insight[] {
  const rank: Record<Insight['severity'], number> = { warn: 0, info: 1 };
  return r.insights
    .map((ins, i) => ({ ins, i }))
    .sort((a, b) => rank[a.ins.severity] - rank[b.ins.severity] || a.i - b.i)
    .map((x) => x.ins);
}
