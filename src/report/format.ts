/**
 * 3_600_000 -> "1h 00m", 3_420_000 -> "57m 00s", 65_000 -> "1m 05s",
 * 2_400 -> "2.4s", 850 -> "850ms", undefined -> "-"
 */
export function humanizeDuration(ms?: number | null): string {
  if (ms === undefined || ms === null || !Number.isFinite(ms) || ms < 0) return '-';
  if (ms < 1000) return `${Math.round(ms)}ms`;
  const totalSec = Math.round(ms / 1000);
  if (totalSec < 60) return `${(ms / 1000).toFixed(1)}s`;
  const minutes = Math.floor(totalSec / 60);
  const sec = totalSec % 60;
  if (totalSec < 3600) return `${minutes}m ${String(sec).padStart(2, '0')}s`;
  const hours = Math.floor(minutes / 60);
  return `${hours}h ${String(minutes % 60).padStart(2, '0')}m`;
}

/** 2_800_000 -> "2.8M", 384_200 -> "384.2k", 912 -> "912", undefined -> "-" */
export function humanizeTokens(n?: number | null): string {
  if (n === undefined || n === null || !Number.isFinite(n)) return '-';
  const sign = n < 0 ? '-' : '';
  const v = Math.abs(n);
  if (v < 1000) return sign + String(Math.round(v));
  const tiers: Array<[number, string]> = [
    [1e9, 'G'],
    [1e6, 'M'],
    [1e3, 'k'],
  ];
  for (const [div, suffix] of tiers) {
    if (v >= div) {
      let s = (v / div).toFixed(1);
      if (s.endsWith('.0')) s = s.slice(0, -2);
      return sign + s + suffix;
    }
  }
  return sign + String(Math.round(v));
}

/** 18.42 -> "$18.42", 0.0023 -> "$0.0023", undefined -> "-" */
export function formatUsd(v?: number | null): string {
  if (v === undefined || v === null || !Number.isFinite(v)) return '-';
  const sign = v < 0 ? '-' : '';
  const a = Math.abs(v);
  if (a === 0) return `${sign}$0.00`; // zero-cost is a known value, not a missing one
  if (a >= 0.01) return `${sign}$${groupThousands(a.toFixed(2))}`;
  // Sub-cent values keep two significant digits without trailing zeros.
  return `${sign}$${trimZeros(a.toPrecision(2))}`;
}

function groupThousands(s: string): string {
  const dot = s.indexOf('.');
  const intPart = dot === -1 ? s : s.slice(0, dot);
  const fracPart = dot === -1 ? '' : s.slice(dot);
  const grouped = intPart.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return grouped + fracPart;
}

function trimZeros(s: string): string {
  if (!s.includes('.')) return s;
  return s.replace(/0+$/, '').replace(/\.$/, '');
}

/** Integer or "-". */
export function num(n?: number | null): string {
  if (n === undefined || n === null || !Number.isFinite(n)) return '-';
  return String(n);
}

/** "43%" — share of `part` in `total`, clamped to [0, 100]. total <= 0 -> "0%". */
export function pct(part: number, total: number, decimals = 0): string {
  return `${pctNum(part, total, decimals)}%`;
}

/** Numeric share (no "%" suffix) for CSS widths; clamped, NaN-safe. */
export function pctNum(part: number, total: number, decimals = 1): number {
  if (!Number.isFinite(part) || !Number.isFinite(total) || total <= 0) return 0;
  const p = Math.min(100, Math.max(0, (part / total) * 100));
  const factor = 10 ** decimals;
  return Math.round(p * factor) / factor;
}

